using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;

namespace CMS.Editor
{
    internal sealed class EntitySlotsSourceService
    {
        internal const string OutputPath = "Assets/_Generated/EntitySlots.cs";

        private static readonly Regex CommentsAndStrings = new Regex(
            "@\"(?:\"\"|[^\"])*\"|\"(?:\\\\.|[^\"\\\\])*\"|//[^\\r\\n]*|/\\*[\\s\\S]*?\\*/");
        private static readonly Regex SourceLayout = new Regex(
            @"\A\s*namespace\s+CMS\s*\.\s*Generated\s*\{\s*public\s+static\s+class\s+EntitySlots\s*\{(?<fields>[\s\S]*)\}\s*\}\s*\z");
        private static readonly Regex FieldDeclaration = new Regex(
            @"public\s+const\s+string\s+(?<name>[A-Z_][A-Z0-9_]*)\s*=\s*(?<value>""(?:\\.|[^""\\\r\n])*"")\s*;");

        private readonly IFileManager _files;

        public EntitySlotsSourceService(IFileManager files)
        {
            _files = files;
        }

        public void Build()
        {
            var keys = new SortedSet<string>(StringComparer.Ordinal);

            foreach (var entry in _files.Find("*" + EntityConstants.FileExtension))
            {
                var index = EntityFileCodec.Index(_files.Load(entry));

                foreach (var segment in index.GetSegments(EntitySlot.Named))
                    keys.Add(segment.Name);
            }

            var fields = BuildFields(keys);

            if (File.Exists(OutputPath) && HasSameFields(File.ReadAllText(OutputPath), fields))
                return;

            var source = new StringBuilder();
            source.AppendLine("// Auto-generated by CMS. Do not edit.");
            source.AppendLine("namespace CMS.Generated");
            source.AppendLine("{");
            source.AppendLine("    public static class EntitySlots");
            source.AppendLine("    {");

            foreach (var field in fields)
                source.AppendLine($"        public const string {field.Key} = {field.Value};");

            source.AppendLine("    }");
            source.AppendLine("}");

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, source.ToString(), new UTF8Encoding(false));
            AssetDatabase.ImportAsset(OutputPath);
        }

        private static SortedDictionary<string, string> BuildFields(IEnumerable<string> keys)
        {
            var names = new HashSet<string>(StringComparer.Ordinal) { "EntitySlots" };
            var fields = new SortedDictionary<string, string>(StringComparer.Ordinal);

            foreach (var key in keys)
            {
                var name = StaticSourceService.GetIdentifier(key);

                if (!names.Add(name))
                {
                    using var hash = SHA256.Create();
                    var suffix = BitConverter.ToString(hash.ComputeHash(Encoding.UTF8.GetBytes(key)))
                        .Replace("-", string.Empty);
                    name += "_" + suffix;

                    while (!names.Add(name))
                        name += "_";
                }

                fields.Add(name, GetStringLiteral(key));
            }

            return fields;
        }

        private static bool HasSameFields(string source, SortedDictionary<string, string> expected)
        {
            // Preserve literals containing comment markers, just as in StaticSourceService.
            source = CommentsAndStrings.Replace(source, match =>
                match.Value.StartsWith("/", StringComparison.Ordinal) ? " " : match.Value);

            var layout = SourceLayout.Match(source);

            if (!layout.Success)
                return false;

            var body = layout.Groups["fields"].Value;
            var actual = new SortedDictionary<string, string>(StringComparer.Ordinal);

            foreach (Match field in FieldDeclaration.Matches(body))
            {
                var name = field.Groups["name"].Value;

                if (actual.ContainsKey(name))
                    return false;

                actual.Add(name, field.Groups["value"].Value);
            }

            // Extra code, malformed fields and duplicates must force regeneration.
            return string.IsNullOrWhiteSpace(FieldDeclaration.Replace(body, string.Empty)) &&
                actual.SequenceEqual(expected);
        }

        private static string GetStringLiteral(string value)
        {
            var literal = new StringBuilder("\"");

            foreach (var character in value)
            {
                switch (character)
                {
                    case '"':
                        literal.Append("\\\"");
                        break;
                    case '\\':
                        literal.Append("\\\\");
                        break;
                    default:
                        if (character < ' ' || character > '~')
                            literal.Append("\\u").Append(((int)character).ToString("X4"));
                        else
                            literal.Append(character);
                        break;
                }
            }

            return literal.Append('"').ToString();
        }
    }
}
