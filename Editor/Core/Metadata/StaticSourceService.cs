using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;

namespace CMS.Editor
{
    internal sealed class StaticSourceService
    {
        internal const string OutputPath = "Assets/_Generated/Content.cs";

        private static readonly Regex CommentsAndStrings = new Regex(
            "@\"(?:\"\"|[^\"])*\"|\"(?:\\\\.|[^\"\\\\])*\"|//[^\\r\\n]*|/\\*[\\s\\S]*?\\*/");
        private static readonly Regex SourceLayout = new Regex(
            @"\A\s*namespace\s+CMS\s*\.\s*Generated\s*\{\s*public\s+static\s+class\s+CmsData\s*\{(?<fields>[\s\S]*)\}\s*\}\s*\z");
        private static readonly Regex FieldDeclaration = new Regex(
            @"public\s+static\s+readonly\s+global\s*::\s*CMS\s*\.\s*ContentId\s+(?<name>[A-Z_][A-Z0-9_]*)\s*=\s*global\s*::\s*CMS\s*\.\s*ContentId\s*\.\s*FromGuid\s*\(\s*""(?<id>[^""]*)""\s*\)\s*;");

        private readonly IMetadataResolver<ContentId> _ids;
        private readonly IRegistrationResolver<StaticSourceIgnore> _ignores;

        public StaticSourceService(IMetadataResolver<ContentId> ids,
            IRegistrationResolver<StaticSourceIgnore> ignores)
        {
            _ids = ids;
            _ignores = ignores;
        }

        public void Build(IEnumerable<FileEntry> entries)
        {
            var ignores = _ignores.GetInstances();
            var names = new HashSet<string>(StringComparer.Ordinal) { "CmsData" };
            var fields = new SortedDictionary<string, Guid>(StringComparer.Ordinal);

            foreach (var entry in entries.OrderBy(entry => entry.Path, StringComparer.Ordinal))
            {
                if (string.Equals(Path.GetFullPath(entry.Path), Path.GetFullPath(OutputPath),
                        StringComparison.OrdinalIgnoreCase))
                    continue;

                var id = _ids.Resolve(entry);
                if (ignores.Any(ignore => ignore.Matches(entry, id)))
                    continue;

                var name = GetIdentifier(Path.GetFileNameWithoutExtension(entry.Path));
                if (!names.Add(name))
                {
                    name += "_" + id.Id.ToString("N").ToUpperInvariant();
                    while (!names.Add(name))
                        name += "_";
                }

                fields.Add(name, id.Id);
            }

            if (File.Exists(OutputPath) && HasSameFields(File.ReadAllText(OutputPath), fields))
                return;

            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by CMS. Do not edit.");
            builder.AppendLine("namespace CMS.Generated");
            builder.AppendLine("{");
            builder.AppendLine("    public static class CmsData");
            builder.AppendLine("    {");
            foreach (var field in fields)
                builder.AppendLine($"        public static readonly global::CMS.ContentId {field.Key} = global::CMS.ContentId.FromGuid(\"{field.Value:D}\");");

            builder.AppendLine("    }");
            builder.AppendLine("}");
            var source = builder.ToString();

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, source, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(OutputPath);
        }

        private static bool HasSameFields(string source, SortedDictionary<string, Guid> expected)
        {
            // Keep string literals intact so comment-like text inside them is not removed.
            source = CommentsAndStrings.Replace(source, match =>
                match.Value.StartsWith("/", StringComparison.Ordinal) ? " " : match.Value);
            var layout = SourceLayout.Match(source);
            if (!layout.Success)
                return false;

            var body = layout.Groups["fields"].Value;
            var actual = new SortedDictionary<string, Guid>(StringComparer.Ordinal);
            foreach (Match field in FieldDeclaration.Matches(body))
            {
                var name = field.Groups["name"].Value;
                if (!Guid.TryParse(field.Groups["id"].Value, out var id) || actual.ContainsKey(name))
                    return false;
                actual.Add(name, id);
            }

            // A partial match must not hide malformed or unsupported declarations.
            return string.IsNullOrWhiteSpace(FieldDeclaration.Replace(body, string.Empty)) &&
                actual.SequenceEqual(expected);
        }

        internal static string GetIdentifier(string name)
        {
            name = Regex.Replace(name, @"([A-Z])([A-Z][a-z])", "$1_$2");
            name = Regex.Replace(name, @"([a-z0-9])([A-Z])", "$1_$2");
            name = Regex.Replace(name, @"\s+", "_");
            var identifier = new string(name.ToUpperInvariant()
                .Select(character => character >= 'A' && character <= 'Z' ||
                    character >= '0' && character <= '9' || character == '_' ? character : '_').ToArray());
            if (identifier.Length == 0)
                return "_";
            return identifier[0] >= '0' && identifier[0] <= '9' ? "_" + identifier : identifier;
        }
    }
}
