using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;

namespace CMS.Editor
{
    internal sealed class StaticSourceService
    {
        internal const string OutputPath = "Assets/_Generated/Content.cs";

        private readonly IMetadataResolver<ContentId> _ids;
        private readonly IRegistrationResolver<StaticSourceIgnore> _ignores;

        public StaticSourceService(IMetadataResolver<ContentId> ids,
            IRegistrationResolver<StaticSourceIgnore> ignores)
        {
            _ids = ids;
            _ignores = ignores;
        }

        public void Build(IEnumerable<FileEntry> entries)
        {
            var ignores = _ignores.GetInstances();
            var names = new HashSet<string>(StringComparer.Ordinal) { "CmsData" };
            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by CMS. Do not edit.");
            builder.AppendLine("namespace CMS.Generated");
            builder.AppendLine("{");
            builder.AppendLine("    public static class CmsData");
            builder.AppendLine("    {");

            foreach (var entry in entries.OrderBy(entry => entry.Path, StringComparer.Ordinal))
            {
                if (string.Equals(Path.GetFullPath(entry.Path), Path.GetFullPath(OutputPath),
                        StringComparison.OrdinalIgnoreCase))
                    continue;

                var id = _ids.Resolve(entry);
                if (ignores.Any(ignore => ignore.Matches(entry, id)))
                    continue;

                var name = GetIdentifier(Path.GetFileNameWithoutExtension(entry.Path));
                if (!names.Add(name))
                {
                    name += "_" + id.Id.ToString("N").ToUpperInvariant();
                    while (!names.Add(name))
                        name += "_";
                }

                builder.AppendLine($"        public static readonly global::CMS.ContentId {name} = global::CMS.ContentId.FromGuid(\"{id.Id:D}\");");
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");
            var source = builder.ToString();
            if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == source)
                return;

            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
            File.WriteAllText(OutputPath, source, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(OutputPath);
        }

        private static string GetIdentifier(string name)
        {
            var identifier = new string(name.ToUpperInvariant()
                .Select(character => character >= 'A' && character <= 'Z' ||
                    character >= '0' && character <= '9' || character == '_' ? character : '_').ToArray());
            if (identifier.Length == 0)
                return "_";
            return identifier[0] >= '0' && identifier[0] <= '9' ? "_" + identifier : identifier;
        }
    }
}
